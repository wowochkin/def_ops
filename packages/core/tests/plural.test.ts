import { describe, expect, it } from 'vitest';
import { countRu, plural } from '../src';

describe('склонение после числа', () => {
  it('одна, несколько, много — по последним цифрам', () => {
    const f = (n: number) => plural(n, 'объект', 'объекта', 'объектов');
    expect([1, 21, 101, 94371].map(f)).toEqual(['объект', 'объект', 'объект', 'объект']);
    expect([2, 3, 4, 22, 94373, 1004].map(f)).toEqual(['объекта', 'объекта', 'объекта', 'объекта', 'объекта', 'объекта']);
    expect([0, 5, 11, 12, 13, 14, 19, 111, 112, 1000].map(f)).toEqual(Array(10).fill('объектов'));
  });
  it('число с разрядами и слово', () => {
    expect(countRu(94373, 'объект', 'объекта', 'объектов')).toBe('94 373 объекта');
    expect(countRu(324313, 'тайл', 'тайла', 'тайлов')).toBe('324 313 тайлов');
    expect(countRu(1, 'участок', 'участка', 'участков')).toBe('1 участок');
  });
});
