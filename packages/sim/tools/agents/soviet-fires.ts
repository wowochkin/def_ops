/** Повторные подготовки для армий, которые есть в сценарии. */
export function repeatedFires(armies: Set<string>): Fire[] {
  return RAW.filter((r) => armies.has(r[1])).map(([at, hq, durationMin, densityPerKm, note]) => ({ at, hq, durationMin, densityPerKm, note }));
}

/** Развёрнуты к началу: советские соединения с задачей наступать с первого часа, стоящие в исходном районе — не дальше
 * 8 км от противника (contactKm 4 км + полполосы). Исходные районы 1 БФ и 1 УФ заняты в ночь на 16.04, атака — через
 * 20–25 мин после начала артподготовки (оперсводка 1 БФ, «Русский архив» т. 15, A; berlin-1945-losses-daily.json). */
export function markDeployed(out: { id: string; side: string; pos: [number, number]; deployed?: boolean }[], orders: { at: unknown; to: string[]; kind: string }[]): number {
  const KX = 111.32 * Math.cos((52.5 * Math.PI) / 180), KY = 110.57;
  const atStart = new Set(orders.filter((o) => (o.at === 0 || o.at === '1945-04-16T05:00') && o.kind === 'attack').flatMap((o) => o.to));
  const de = out.filter((o) => o.side === 'de');
  let n = 0;
  for (const o of out) {
    if (o.side !== 'su' || !atStart.has(o.id)) continue;
    const near = de.some((e) => Math.hypot((e.pos[0] - o.pos[0]) * KX, (e.pos[1] - o.pos[1]) * KY) <= 8);
    if (near) { o.deployed = true; n++; }
  }
  return n;
}

