/**
 * Рубрикатор базы знаний: нумерованное дерево тем (1 → 1.2 → 1.2.6). Запись стоит в одной или нескольких
 * рубриках (главная — первая). Категория записи отвечает на вопрос «что это» (бой, дивизия, танк), рубрика —
 * «о чём это» (Берлинская операция › Штурм Берлина; Тактика › Бой в городе). Модель при разборе документов
 * назначает рубрики из этого же списка.
 */
import type { Entry } from './schema';

export interface Rubric { code: string; title: string; description?: string; children?: Rubric[] }

const r = (code: string, title: string, children?: Rubric[], description?: string): Rubric => ({ code, title, ...(children ? { children } : {}), ...(description ? { description } : {}) });

