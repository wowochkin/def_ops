const flat: Rubric[] = [];
const parentOf = new Map<string, string>();
(function walk(list: Rubric[], parent?: string) { for (const x of list) { flat.push(x); if (parent) parentOf.set(x.code, parent); if (x.children) walk(x.children, x.code); } })(RUBRICS);
const byCode = new Map(flat.map((x) => [x.code, x]));

export const rubric = (code: string) => byCode.get(code);
export const RUBRIC_CODES = flat.map((x) => x.code);
/** Рубрики-листья (их назначает модель). */
export const LEAF_RUBRICS = flat.filter((x) => !x.children).map((x) => x.code);
/** Путь: «Операции и сражения › Берлинская операция › Штурм Берлина». */
export function rubricPath(code: string): Rubric[] {
  const out: Rubric[] = [];
  for (let c: string | undefined = code; c; c = parentOf.get(c)) { const x = byCode.get(c); if (x) out.unshift(x); }
  return out;
}
/** Входит ли рубрика code в рubric prefix (сама или вложенная). */
export const within = (code: string, prefix: string) => code === prefix || code.startsWith(prefix + '.');

const MONTH_RUBRIC: Record<string, string> = { '01': '8.1', '02': '8.1', '03': '8.2', '04': '8.2', '05': '8.3' };
const ECHELON: Record<string, string> = { фронт: '1', 'высшее командование': '1', армия: '2', корпус: '3', дивизия: '4', бригада: '4', полк: '5', батальон: '5', battlegroup: '5' };

/**
 * Рубрики записи, если не заданы явно: по категории, подгруппе и фактам. Начальное наполнение и записи из
 * документов без рубрик получают их отсюда.
 */
export function defaultRubrics(e: Pick<Entry, 'id' | 'category' | 'group' | 'title' | 'facts' | 'period' | 'relations'>): string[] {
  const fact = (k: string) => e.facts?.find((f) => f.key === k)?.value ?? '';
  const t = e.title.toLowerCase();
  switch (e.category) {
    case 'operations': return [/висл/i.test(e.title) || e.id.includes('vistula') ? '1.1' : '1.2'];
    case 'battles': {
      const op = e.relations?.find((x) => x.type === 'part_of')?.target ?? '';
      return [op.includes('vistula') ? '1.1' : '1.2'];
    }
    case 'formations': {
      const side = e.group === 'de' ? '2.2' : '2.1';
      return [`${side}.${ECHELON[fact('echelon')] ?? '5'}`];
    }
    case 'commanders': return [e.group === 'de' ? '7.2' : '7.1'];
    case 'organization': {
      if (e.group === 'model') return ['9.7'];
      const out: string[] = [];
      if (/темп/.test(t)) out.push('3.4.1');
      if (/плотност/.test(t)) out.push('3.4.2');
      if (/потер/.test(t)) out.push('3.4.3');
      if (/управлен|задержк/.test(t)) out.push('3.4.4');
      if (/тыл|снабжен/.test(t)) out.push('5.1');
      if (/переправ/.test(t)) out.push('5.3', '3.2.4');
      if (/инженер/.test(t)) out.push('3.3.4');
      if (/артиллер/.test(t)) out.push('3.3.1');
      if (/штурм|город/.test(t)) out.push('3.2.3');
      if (/общие черты/.test(t)) out.push('3.4.5');
      if (/прочие норматив/.test(t)) out.push('3.4.4');
      return out.length ? out : ['3.1'];
    }
    case 'equipment': return [({ armor: '4.1', artillery: '4.2', infantry: '4.3', air: '4.4' } as Record<string, string>)[e.group ?? ''] ?? '4.3'];
    case 'terrain': {
      const g = ({ rivers: '6.1', lines: '6.4', cities: '6.3', areas: '6.2' } as Record<string, string>)[e.group ?? ''] ?? '6.2';
      if (g === '6.4' && /берлин|цитадел|обвод|сектор/i.test(e.title)) return [g, '1.2.6'];
      if (/полоса|позиция|зеелов|одербрух/i.test(e.title)) return [g, '1.2.2'];
      return [g];
    }
    case 'chronology': {
      const m = (e.period?.from ?? fact('date')).slice(5, 7);
      return [MONTH_RUBRIC[m] ?? '8.2'];
    }
    case 'sources': {
      if (e.group === 'uploaded' || e.id.startsWith('doc:')) return ['9.5'];
      const ref = fact('ref') + ' ' + e.title;
      if (/записки|воспоминан|мемуар|memoir|erinnerung/i.test(ref)) return ['9.2'];
      if (e.group === 'web') return ['9.4'];
      if (/вывод составителя|интерполяц/i.test(ref)) return ['9.6'];
      if (/директив|ЦАМО|КТБ|KTB|IfZ|gazetteer|OSM|Nominatim|OOB|Nafziger|Lexikon|таблиц/i.test(ref)) return ['9.1'];
      return ['9.3'];
    }
  }
  return [];
}

/** Рубрики записи: заданные явно или вычисленные. */
export const rubricsOf = (e: Entry): string[] => (e.rubrics?.length ? e.rubrics : defaultRubrics(e));
