/** Час момента в прогоне и сверка с историей. */
export function momentHour(data: RunData, m: Moment): { h: number; hist: string | null; reached: boolean } {
  const { trace, history } = data;
  const ev = m.milestone ? history.events?.find((e) => e.id === m.milestone) : undefined;
  const a = ev ? milestoneHour(trace, ev) : null;
  const h = a ?? Math.max(0, Math.min(trace.hours, hourOf(trace.start, m.at)));
  return { h, hist: ev?.date ?? null, reached: a !== null };
}
