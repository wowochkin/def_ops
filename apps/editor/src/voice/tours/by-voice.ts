/**
 * Честный шаг каждого тура раздела: что здесь можно голосом. Голосом в разделах (кроме командования) пока доступны
 * переход, вкладки и тур — остальное делается мышью; тур так и говорит.
 */
import type { TourStep } from './index';

export function byVoice(o: { tabs?: boolean; example: string; also?: string }): TourStep {
  return {
    target: 'voice',
    via: 'rail',
    title: 'Что здесь можно голосом',
    text: `Здесь голосом можно: перейти в другой раздел${o.tabs ? ', переключить вкладку' : ''}, пройти этот тур ещё раз; остальное — мышью.`
      + (o.also ? ` ${o.also}` : ''),
    example: o.example,
    more: 'Что я понимаю в этом разделе, видно в панели голоса, в списке «Что можно сказать». Можно и спросить: «Штаб, что я могу?»',
  };
}
