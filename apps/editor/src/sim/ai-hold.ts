/**
 * Штаб противника после хода ждёт доклада посредника голосом: окно шлёт umpire-done, когда доклад готов (или голос не
 * слышит и доклада моделью нет). Иначе запрос штаба встал бы к модели первым, и посредник ждал бы за ним. Не дольше
 * UMPIRE_HOLD_MS (окно не ответило — запуск сам): ответ модели посредника (до трёх попыток) и заготовка звука разбора
 * (до 90 с, voice/umpire.ts). Решение противника нужно лишь к следующему ходу, поэтому очередь.
 */
export const UMPIRE_HOLD_MS = 240_000;

export function aiHold(start: () => void, ms = UMPIRE_HOLD_MS) {
  let t: ReturnType<typeof setTimeout> | null = null;
  const drop = () => { if (t) clearTimeout(t); t = null; };
  return {
    /** Ход посчитан: штаб противника — после доклада посредника. */
    hold(): void { drop(); t = setTimeout(() => { t = null; start(); }, ms); },
    /** Доклад готов или новый ход — запустить штаб противника сейчас (не держали — ничего). */
    release(): void { if (!t) return; drop(); start(); },
    /** Штаб противника запускают иначе (смена режима, «повтори запрос») — перестать держать. */
    drop,
    held: () => t !== null,
  };
}
