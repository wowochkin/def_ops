import { describe, expect, it } from 'vitest';
import { applyStress } from '../src/expo/stress';
import { placeWordForms } from '../src/expo/stress-places';
import STRESS from '../src/expo/bank-data/stress.json';

describe('падежи топонимов в словаре озвучки', () => {
  it('переносит известное ударение на падежи, включая запись только в родительном', () => {
    // Только исходные формы: пополнение рабочего словаря не превращает проверку склонения в точный поиск.
    const words = { Кетцин: 'К+етцин', Шторкова: 'Шт+оркова', Бауцен: 'Б+ауцен', Каменц: 'К+аменц' };
    expect(applyStress('к Кетцину, под Кетцином, в Кетцине; к Шторкову; у Бауцена и Каменца', words))
      .toBe('к К+етцину, под К+етцином, в К+етцине; к Шт+оркову; у Б+ауцена и К+аменца');
  });

  it('не исправляет пользовательские формы и не додумывает противоречивые семейства', () => {
    expect(applyStress('Мюнхеберг Мюнхеберга Мюнхебергу', STRESS.words))
      .toBe('М+юнхеберг Мюнхеб+ерга Мюнхебергу');
    expect(applyStress('Каменц Каменца', { Каменц: 'К+аменц', Каменца: 'Кам+енца' }))
      .toBe('К+аменц Кам+енца');
    expect(applyStress('Кетцину Кетцином', { Кетцин: 'К+етцин', Кетцину: 'Кетцин+у' }))
      .toBe('Кетцин+у Кетцином');
  });

  it('не распространяет ударения на обычные слова, производные и другие географические названия', () => {
    // Проверяем вывод форм из фиксированного набора, независимо от новых явных записей рабочего словаря.
    const words = { игры: '+игры', Пойму: 'П+ойму', Кетцин: 'К+етцин' };
    expect(applyStress('игры играми; Пойму поймать; Кетцинский Кетцинуево; Шарлоттенбург Тиргартен', words))
      .toBe('+игры играми; П+ойму поймать; Кетцинский Кетцинуево; Шарлоттенбург Тиргартен');
  });

  it('словарь имеет приоритет над пометкой из текста, неизвестные пометки сохраняются', () => {
    expect(applyStress('Кетци́ну Кетц+ину К+етцину Незна́емый', STRESS.words))
      .toBe('К+етцину К+етцину К+етцину Незна́емый');
  });

  it('сохраняет точные пользовательские составные названия и фразы', () => {
    expect(applyStress('у Красной площади, Красной площади и Бад-Фрайенвальде', {
      'Красной площади': 'Кр+асной пл+ощади', 'Бад-Фрайенвальде': 'Бад-Фр+айенвальде',
    })).toBe('у Кр+асной пл+ощади, Кр+асной пл+ощади и Бад-Фр+айенвальде');
  });

  it('не придумывает мужские падежи и окончания для названий на шипящие', () => {
    for (const word of ['Калиш', 'Лович', 'Быдгощ', 'Ходзеж']) expect(placeWordForms(word)).toEqual([word]);
    expect(applyStress('Калиш Калиша Калишем', { Калиш: 'К+алиш', Калишем: 'К+алишем' }))
      .toBe('К+алиш Калиша К+алишем');
  });
});
