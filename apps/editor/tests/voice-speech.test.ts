describe('speakable: количественные в родительном падеже', () => {
  it.each([
    [1, 'одного'], [2, 'двух'], [21, 'двадцати одного'], [99, 'девяноста девяти'], [100, 'ста'], [101, 'ста одного'], [200, 'двухсот'],
    [350, 'трёхсот пятидесяти'], [1000, 'тысячи'], [1500, 'тысячи пятисот'], [2000, 'двух тысяч'], [21000, 'двадцати одной тысячи'],
    [12000, 'двенадцати тысяч'], [999999, 'девятисот девяноста девяти тысяч девятисот девяноста девяти'],
  ])('%i → %s', (n, w) => expect(cardinalGen(n)).toBe(w));
  it('женский род и границы', () => {
    expect(cardinalGen(1, true)).toBe('одной');
    expect(cardinalGen(221, true)).toBe('двухсот двадцати одной');
    expect(cardinalGen(0)).toBeNull();
    expect(cardinalGen(1e6)).toBeNull();
    expect(cardinalGen(1.5)).toBeNull();
  });
  it('в тексте после предлогов с родительным', () => {
    expect(speakable('Около 200 танков.')).toBe('Около двухсот танков.');
    expect(speakable('Около 1 500 орудий.')).toBe('Около тысячи пятисот орудий.');
    expect(speakable('Более 100 танков и САУ.')).toBe('Более ста танков и САУ.');
    expect(speakable('Около 21 пушки.')).toBe('Около двадцати одной пушки.');
    expect(speakable('Около 21 танка.')).toBe('Около двадцати одного танка.');
    expect(speakable('До 12 тыс. чел.')).toBe('До двенадцати тысяч человек');
    expect(speakable('До 150 км.')).toBe('До ста пятидесяти километров.');
    expect(speakable('До 2 линии.')).toBe('До второй линии.');
  });
  it('строка разведсводки (IntelReport.estimate)', () => {
    expect(speakable(estimate({ personnel: 12500, tanks: 200, guns: 1000 })))
      .toBe('до десяти тысяч человек, около двухсот танков и САУ, около тысячи орудий и минометов');
    expect(speakable(estimate({ personnel: 3000, tanks: 40, guns: 60 })))
      .toBe('до трёх тысяч человек, около сорока танков и САУ, около шестидесяти орудий и минометов');
  });
});

describe('speakable: названия соединений трёх сценариев', () => {
  const names = [...new Set([berlin, city, vistula].flatMap((s) => s.formations.map((f) => f.name)))];
  const HEADS: Record<string, 'm' | 'f'> = { корпус: 'm', полк: 'm', фронт: 'm', район: 'm', отряд: 'm', батальон: 'm', дивизия: 'f', армия: 'f', бригада: 'f', группа: 'f' };
  const ADJ = { m: /(?:ый|ий|ой|ьего|ого)$/, f: /(?:ая|яя|ья)$/ };
  const OTHER = { m: /(?:ая|яя|ое|ее|ую)$/, f: /(?:ый|ий|ой|ое|ее|ую)$/ };

  it('есть что проверять', () => expect(names.length).toBeGreaterThan(100));

  it('нет цифр, латиницы, сокращений и рассогласования рода перед существительным', () => {
    const bad: string[] = [];
    for (const name of names) {
      const out = speakable(name.replace(/\s*\([^)]*[A-Za-z][^)]*\)/g, ''));
      if (/\d|гв\.|(?<!\p{L})(?:ск|тк|мк|кк|сд|пд|тд|мд|тбр|ТА|УА)(?!\p{L})/u.test(out)) bad.push(`остаток: ${name} → ${out}`);
      const words = out.replace(/[«»()",]/g, ' ').split(/\s+/).filter(Boolean);
      words.forEach((w, i) => {
        const g = HEADS[w.toLowerCase()];
        if (!g || i === 0) return;
        // прилагательные и порядковое сразу перед существительным
        for (let j = i - 1; j >= 0; j--) {
          const p = words[j];
          if (!(ADJ.m.test(p) || ADJ.f.test(p) || OTHER.m.test(p) || OTHER.f.test(p))) break;
          if (OTHER[g].test(p) && !ADJ[g].test(p)) bad.push(`род: ${name} → ${out} («${p}» перед «${w}»)`);
        }
      });
    }
    expect(bad).toEqual([]);
  });

  it('эталонные названия', () => {
    const say = (s: string) => speakable(s);
    expect(say('29-й гвардейский стрелковый корпус (8 гв. А)')).toBe('двадцать девятый гвардейский стрелковый корпус (восьмая гвардейская армия)');
    expect(say('91-й стрелковый корпус (69 А)')).toBe('девяносто первый стрелковый корпус (шестьдесят девятая армия)');
    expect(say('Армейский подвижной отряд 5 УА (220 тбр, 396 отсап)'))
      .toBe('Армейский подвижной отряд пятая ударная армия (двести двадцатая танковая бригада, триста девяносто шестой отдельный сапёрный батальон)');
    expect(say('LVI танковый корпус')).toBe('пятьдесят шестой танковый корпус');
    expect(say('4-я гвардейская танковая армия')).toBe('четвёртая гвардейская танковая армия');
  });
});

describe('speakable: раунд 1 — предлоги места и направления, римские номера', () => {
  it.each([
    ['Был в 3-й тбр.', 'Был в третьей танковой бригаде.'],
    ['Бой в 5 А.', 'Бой в пятой армии.'],
    ['Бой на 69 А.', 'Бой на шестьдесят девятой армии.'],
    ['Удар за 5 ТА.', 'Удар за пятую танковую армию.'],
    ['Удар через 3 тбр.', 'Удар через третью танковую бригаду.'],
    ['Выйти на 29 гв. ск.', 'Выйти на двадцать девятый гвардейский стрелковый корпус.'],
  ])('%s', (src, out) => expect(speakable(src)).toBe(out));
  it('число + «А» с цифрой или буквой — не армия; «тк»/«ак» без номера не раскрываются', () => {
    expect(speakable('Лист 5 A4.')).toBe('Лист пять.');
    expect(speakable('Выехал тк нет.')).toBe('Выехал тк нет.');
    expect(speakable('Это ак.')).toBe('Это ак.');
  });
  it('множественное число после «гв.»', () => {
    expect(speakable('Прибыли гв. стрелковые корпуса.')).toBe('Прибыли гвардейские стрелковые корпуса.');
    expect(speakable('Нет гв. стрелковых корпусов.')).toBe('Нет гвардейских стрелковых корпусов.');
  });
  it.each([
    ['XXXXVI танковый корпус', 'сорок шестой танковый корпус'],
    ['XXXX тк', 'сороковой танковый корпус'],
    ['XXIII гв. ск', 'двадцать третий гвардейский стрелковый корпус'],
    ['Из XXXXVIII тк.', 'Из сорок восьмого танкового корпуса.'],
    ['XXIV танковый корпус (группа Неринга)', 'двадцать четвёртый танковый корпус (группа Неринга)'],
  ])('римские номера: %s', (src, out) => expect(speakable(src)).toBe(out));
  it('слово перед сокращением не повторяется', () => {
    expect(speakable('Фронт 3 УФ.')).toBe('Фронт третий Украинский.');
    expect(speakable('Командующий фронта 3 УФ.')).toBe('Командующий фронта третьего Украинского.');
  });
  it('римский номер названия сценария не теряется', () => {
    const names = [...new Set([berlin, city, vistula].flatMap((s) => s.formations.map((f) => f.name)))].filter((n) => /^[IVXLC]+ /.test(n));
    expect(names.length).toBeGreaterThan(10);
    for (const n of names) expect(speakable(n).split(' ')[0], n).not.toBe(n.split(' ')[1].toLowerCase());
  });
});
