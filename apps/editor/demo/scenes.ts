/** Привязка образца №1: пиксель = A·меркатор + b (МНК по 32 городам). */
export const A1 = { a: 87875.2247, b: 4524.5529, c: -2660.1709, d: 87717.5109, e: -48215.3508, f: -26827.0877 };
function pxToLngLat1([x, y]: XY): LngLat {
  const { a, b, c, d, e, f } = A1;
  const det = a * d - b * c;
  const X = x - e, Y = y - f;
  return inverseMercator([(d * X - b * Y) / det, (-c * X + a * Y) / det]);
}
export function lngLatToPx1(ll: LngLat): XY {
  const m = mercator(ll);
  return [A1.a * m[0] + A1.b * m[1] + A1.e, A1.c * m[0] + A1.d * m[1] + A1.f];
}

