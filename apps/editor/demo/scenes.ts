/** Пропорционально изменить ширину стрелки (длины наконечника тоже). */
function scaleArrow(f: ArrowFeature, k: number) {
  const s = f.style;
  s.tailWidth *= k; s.neckWidth *= k; s.headWidth *= k; s.headLength *= Math.sqrt(k); s.barbSweep *= Math.sqrt(k);
}

