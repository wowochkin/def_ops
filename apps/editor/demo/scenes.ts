/** Аффинная привязка растра: пиксель = M·меркатор + t. */
export function affine(a: number, b: number, c: number, d: number, e: number, f: number) {
  const det = a * d - b * c;
  return {
    toLL: ([x, y]: XY): LngLat => {
      const X = x - e, Y = y - f;
      return inverseMercator([(d * X - b * Y) / det, (-c * X + a * Y) / det]);
    },
    toPx: (ll: LngLat): XY => {
      const m = mercator(ll);
      return [a * m[0] + b * m[1] + e, c * m[0] + d * m[1] + f];
    },
  };
}

